-- 邀请制（B 方案）：每个用户注册后自动拿到邀请名额，老用户自己发码邀请别人。
--
-- 为什么码只存 hash：
--   邀请码等价于「注册通行证」，而注册是拿到一个完整账号的唯一入口。明文落库意味着一次
--   只读泄露（备份/psql/日志/误发 dump）就等于把全站注册权发出去，而且泄露后无法区分
--   哪些码已被外人看到。所以库里只存 HMAC-SHA256(normalize(code))，
--   明文只在创建响应 / 运维 CLI 的 stdout 出现一次。
--   HMAC 的 key 来自应用（INVITE_PEPPER|SESSION_SECRET），所以「只拿到库的人」造不出可用码。
--   代价：轮换 INVITE_PEPPER / SESSION_SECRET 会让历史码全部失效——这正是怀疑泄漏时
--   需要的失败模式，写在这里免得以后有人以为换 key 无害。
--
-- 为什么额度单独一张表：
--   quota（还能邀请几个人）是账号属性，和某个码的生命周期无关：码被吊销了，
--   已经被邀请进来的人仍然在。把 quota 记在 invite_codes 上会导致「吊销=退名额」这种
--   能刷名额的漏洞。
--
-- 为什么 max_uses 上限是 100：
--   单个码的用途是「一次性发给一小群人」；要大规模放人应该用站务码（owner_user_id NULL），
--   而不是让一个码无限可用。上限同时把「被分享到公开群」的损失封顶。
--
-- 为什么不给 mcp_writer 任何权限：
--   AI 侧只需要 events + 读模型（[C4]）。邀请码/额度是账号治理面，
--   给 AI 任何一条读写路径都等于把「谁能注册」交给 AI。

-- ---------------------------------------------------------------------------
-- 邀请码
-- ---------------------------------------------------------------------------
-- id 用 IDENTITY 而不是 BIGSERIAL：identity 序列归列所有，不会出现
-- 「新表建了、序列忘了 GRANT」这种部署期才发现的问题（021 就踩过 GRANT 那条坑）。
CREATE TABLE IF NOT EXISTS invite_codes (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  -- NULL = 站务码（不占任何人的名额）
  owner_user_id BIGINT REFERENCES principals(id) ON DELETE SET NULL,
  code_hash     TEXT NOT NULL UNIQUE,
  -- 只用于「我的邀请」里显示 AIO-7K2M-****，够用户认出是哪张码，不足以重放
  code_prefix   TEXT NOT NULL DEFAULT '',
  max_uses      INT  NOT NULL CHECK (max_uses BETWEEN 1 AND 100),
  used_count    INT  NOT NULL DEFAULT 0 CHECK (used_count >= 0),
  expires_at    TIMESTAMPTZ,
  revoked_at    TIMESTAMPTZ,
  note          TEXT NOT NULL DEFAULT '',
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 每个用户同时只有 1 个有效码（应用层在同一事务里先吊销旧码再插新码）。
-- 这个索引只用于「按 owner 找当前有效码」的读路径与吊销扫描，
-- 不是唯一约束：吊销过的历史码必须留着（审计与「这张码发过谁」要能追）。
CREATE INDEX IF NOT EXISTS invite_codes_owner_active_idx
  ON invite_codes (owner_user_id) WHERE revoked_at IS NULL;

-- 换发/轮换时的扫描：很久以前就过期、一直没被吊销的码不该被误判成「当前有效」
CREATE INDEX IF NOT EXISTS invite_codes_expires_idx
  ON invite_codes (expires_at) WHERE revoked_at IS NULL;

-- ---------------------------------------------------------------------------
-- 兑换记录：谁用了哪张码注册进来（邀请人「看到被邀请人」的数据源）
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS invite_redemptions (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code_id      BIGINT NOT NULL REFERENCES invite_codes(id) ON DELETE CASCADE,
  -- 冗余存一份 inviter_id：邀请人要看自己被邀请的人，这条查询不能依赖
  -- invite_codes 还活着（码可以删、owner 可以注销）
  inviter_id   BIGINT REFERENCES principals(id) ON DELETE SET NULL,
  -- 一个账号只能被邀请一次：并发兑换 + 重放都要靠这条唯一约束兜底
  principal_id BIGINT NOT NULL UNIQUE REFERENCES principals(id) ON DELETE CASCADE,
  -- 只存 HMAC：审计需要「同一个邮箱/同一台机器是否反复注册」，但不需要明文
  email_hash   TEXT,
  ip_hash      TEXT,
  redeemed_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS invite_redemptions_code_idx ON invite_redemptions (code_id);
-- 「我的邀请」的主查询：WHERE inviter_id = $1 ORDER BY redeemed_at DESC
CREATE INDEX IF NOT EXISTS invite_redemptions_inviter_idx ON invite_redemptions (inviter_id, redeemed_at DESC);

-- ---------------------------------------------------------------------------
-- 每人邀请额度
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS user_invite_quotas (
  principal_id BIGINT PRIMARY KEY REFERENCES principals(id) ON DELETE CASCADE,
  quota        INT NOT NULL DEFAULT 3 CHECK (quota >= 0),
  used         INT NOT NULL DEFAULT 0 CHECK (used >= 0),
  updated_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  -- 额度不能被用穿：并发兑换的最终防线（应用层还有 SELECT ... FOR UPDATE）
  CONSTRAINT user_invite_quotas_used_le_quota CHECK (used <= quota)
);

-- 回填：迁移前就存在的所有人类账号都拿默认 3 个名额。
-- 用 type='user' 而不是「有 user_accounts 行」：AI 也挂在 principals 上，
-- 但 AI 不该有邀请权（AI 注册走 AGENT_SIGNUP_* 的独立通道）。
INSERT INTO user_invite_quotas (principal_id, quota, used, updated_at)
SELECT p.id, 3, 0, now()
  FROM principals p
 WHERE p.type = 'user'
ON CONFLICT (principal_id) DO NOTHING;

-- ---------------------------------------------------------------------------
-- 审计：append-only
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS invite_audit (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  -- 不设 FK：actor 账号可能被删，审计行必须留着（和 events 的「只追加」同一条原则）
  actor_id     BIGINT,
  action       TEXT NOT NULL,
  code_id      BIGINT,
  principal_id BIGINT,
  -- 只放元数据（max_uses / expires_in_days / 被吊销的旧码 id 列表 / 失败原因），
  -- 绝不放明文码——审计表通常会被单独导出做分析，明文放进去等于第二个泄漏点
  meta         JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS invite_audit_created_idx ON invite_audit (created_at DESC);
CREATE INDEX IF NOT EXISTS invite_audit_code_idx ON invite_audit (code_id) WHERE code_id IS NOT NULL;

-- append-only 用触发器兜住，而不是靠「大家都记得别 UPDATE」：
-- 审计表一旦能被改写，它证明不了任何事。
CREATE OR REPLACE FUNCTION qm_invite_audit_append_only() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'invite_audit 是 append-only：不允许 %', TG_OP
    USING ERRCODE = 'check_violation';
END $$;

DROP TRIGGER IF EXISTS invite_audit_append_only ON invite_audit;
CREATE TRIGGER invite_audit_append_only
  BEFORE UPDATE OR DELETE ON invite_audit
  FOR EACH ROW EXECUTE FUNCTION qm_invite_audit_append_only();

-- ---------------------------------------------------------------------------
-- 授权
--   002_grants.sql 的 GRANT ALL ON ALL TABLES 只覆盖「当时已存在的表」，
--   新表必须显式补，否则部署机上的 qqmini_app 会在第一次创建邀请码时 permission denied。
-- ---------------------------------------------------------------------------
DO $$
DECLARE s record;
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'qqmini_app') THEN
    EXECUTE 'GRANT ALL PRIVILEGES ON invite_codes, invite_redemptions, user_invite_quotas, invite_audit TO qqmini_app';
    -- identity 序列：显式补，别赌「identity 不需要额外授权」
    FOR s IN
      SELECT c.relname
        FROM pg_class c
        JOIN pg_depend d ON d.objid = c.oid AND d.deptype IN ('i', 'a')
        JOIN pg_class t ON t.oid = d.refobjid
       WHERE c.relkind = 'S' AND t.relname IN ('invite_codes', 'invite_redemptions', 'invite_audit')
    LOOP
      EXECUTE format('GRANT USAGE, SELECT ON SEQUENCE %I TO qqmini_app', s.relname);
    END LOOP;
  END IF;
EXCEPTION WHEN insufficient_privilege THEN
  RAISE NOTICE '跳过授权：当前角色无权修改其它角色权限（应由超级用户执行）';
END $$;

-- [C4] 明确收口：AI 侧不该有任何邀请码/额度权限。
-- 即使有人手滑跑过 GRANT ALL ... TO mcp_writer，这个 REVOKE 也把它收回来。
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'mcp_writer') THEN
    EXECUTE 'REVOKE ALL PRIVILEGES ON invite_codes, invite_redemptions, user_invite_quotas, invite_audit FROM mcp_writer';
  END IF;
EXCEPTION WHEN insufficient_privilege THEN
  RAISE NOTICE '跳过回收：当前角色无权修改其它角色权限（应由超级用户执行）';
END $$;
